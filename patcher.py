"""Install the authored RGB add-on using a locally supplied Umbra runtime.

No vendor code is imported/executed and no device is opened by this program.
The only generated bytecode shipped here is compiled from our bootstrap.py.
"""
import argparse
import base64
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import sys
import zlib


VERSION = "0.2.0"
SUPPORTED_SHA256 = "974f28ff684091520bb742cf4a24dabd726c483b08094ded871ab87f90ab5e25"
SUPPORTED_VERSION = "V3.5.5_09.03"
SOURCE_EXE = "Sync_light.exe"
OUTPUT_EXE = "Umbra-RGB-Addon.exe"
MAGIC = b"MEI\x0c\x0b\x0a\x0b\x0e"
COOKIE = struct.Struct("!8sIIII64s")
TOC_HEADER = struct.Struct("!IIIIBc")
ROOT = Path(__file__).resolve().parent
PAYLOAD_FILES = ("umbra_rgb_diagnostic_hook.py", "jonsbo_compatibility.py")
REQUIRED_RUNTIME = ("python38.dll", "base_library.zip", "PySide2", "shiboken2")


class PatchError(ValueError):
    """Unsupported input; never guess at a different vendor format/version."""


@dataclass(frozen=True)
class Entry:
    name: str
    payload: bytes
    raw_size: int
    compressed: int
    kind: bytes


@dataclass(frozen=True)
class Archive:
    prefix: bytes
    entries: tuple
    python_version: int
    library: bytes


@dataclass(frozen=True)
class PreparedInstall:
    source: Path
    destination: Path
    original_data: bytes
    patched_data: bytes
    original_main: bytes
    payloads: dict


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def parse_archive(data):
    """Parse bounded CArchive records as data; never unmarshal vendor code."""
    cookie_at = data.rfind(MAGIC)
    if cookie_at < 0 or cookie_at + COOKIE.size > len(data):
        raise PatchError("Missing or truncated PyInstaller cookie")
    magic, size, toc_offset, toc_size, version, library = COOKIE.unpack_from(data, cookie_at)
    start = cookie_at + COOKIE.size - size
    if (magic != MAGIC or start < 0 or size < COOKIE.size
            or toc_offset > size - COOKIE.size
            or toc_size != cookie_at - start - toc_offset):
        raise PatchError("Invalid PyInstaller archive bounds")
    cursor, toc_end = start + toc_offset, cookie_at
    entries, names = [], set()
    while cursor < toc_end:
        if cursor + TOC_HEADER.size > toc_end:
            raise PatchError("Truncated archive table entry")
        entry_size, offset, compressed_size, raw_size, compressed, kind = TOC_HEADER.unpack_from(data, cursor)
        if (entry_size < TOC_HEADER.size + 1 or cursor + entry_size > toc_end
                or offset > toc_offset or compressed_size > toc_offset - offset
                or compressed not in (0, 1)):
            raise PatchError("Invalid archive table entry bounds")
        label = data[cursor + TOC_HEADER.size:cursor + entry_size]
        if b"\0" not in label:
            raise PatchError("Unterminated archive entry name")
        name_bytes, _, padding = label.partition(b"\0")
        if not name_bytes or any(padding):
            raise PatchError("Invalid archive entry name padding")
        try:
            name = name_bytes.decode("utf-8")
        except UnicodeDecodeError as error:
            raise PatchError("Invalid archive entry name encoding") from error
        if name in names:
            raise PatchError("Duplicate archive entry name: " + name)
        names.add(name)
        payload = data[start + offset:start + offset + compressed_size]
        if not compressed and len(payload) != raw_size:
            raise PatchError("Uncompressed entry size mismatch")
        entries.append(Entry(name, payload, raw_size, compressed, kind))
        cursor += entry_size
    if cursor != toc_end or not entries:
        raise PatchError("Invalid or empty archive table")
    main = [entry for entry in entries if entry.name == "Sync_light"]
    if len(main) != 1 or main[0].kind != b"s":
        raise PatchError("Expected one Sync_light script entry")
    if version != 308 or library.rstrip(b"\0").lower() != b"python38.dll":
        raise PatchError("Only the verified Python 3.8 vendor runtime is supported")
    return Archive(data[:start], tuple(entries), version, library)


def repack_archive(data, bootstrap_bytes):
    """Replace only the main wrapper; retain other compressed payloads exactly."""
    archive = parse_archive(data)
    out, toc = bytearray(archive.prefix), bytearray()
    original_main = None
    for entry in archive.entries:
        payload, raw_size, compressed = entry.payload, entry.raw_size, entry.compressed
        if entry.name == "Sync_light":
            if entry.raw_size > 64 * 1024 * 1024:
                raise PatchError("Unexpectedly large main script")
            try:
                original_main = zlib.decompress(payload) if compressed else payload
            except zlib.error as error:
                raise PatchError("Invalid compressed main script") from error
            if len(original_main) != entry.raw_size:
                raise PatchError("Main script size mismatch")
            raw_size, compressed = len(bootstrap_bytes), 1
            payload = zlib.compress(bootstrap_bytes, 9)
        offset = len(out) - len(archive.prefix)
        out.extend(payload)
        label = entry.name.encode("utf-8") + b"\0"
        entry_size = (TOC_HEADER.size + len(label) + 15) // 16 * 16
        toc.extend(TOC_HEADER.pack(entry_size, offset, len(payload), raw_size,
                                   compressed, entry.kind))
        toc.extend(label + bytes(entry_size - TOC_HEADER.size - len(label)))
    toc_offset = len(out) - len(archive.prefix)
    out.extend(toc)
    size = len(out) - len(archive.prefix) + COOKIE.size
    out.extend(COOKIE.pack(MAGIC, size, toc_offset, len(toc),
                           archive.python_version, archive.library))
    # Original trailing certificate/overlay is not valid for a modified copy.
    return bytes(out), original_main


def verified_source(source):
    source = Path(source).resolve()
    executable = source / SOURCE_EXE
    if not source.is_dir() or not executable.is_file():
        raise PatchError("Source must contain the original Sync_light.exe")
    data = executable.read_bytes()
    actual = sha256(data)
    if actual != SUPPORTED_SHA256:
        raise PatchError("Unsupported or already modified Umbra executable. Expected %s SHA256 %s; got %s"
                         % (SUPPORTED_VERSION, SUPPORTED_SHA256, actual))
    parse_archive(data)
    return data


def load_bootstrap(folder=None):
    folder = ROOT if folder is None else Path(folder)
    metadata = json.loads((folder / "bootstrap38.json").read_text(encoding="utf-8"))
    if (not isinstance(metadata, dict) or metadata.get("python") != [3, 8]
            or metadata.get("marshal_version") != 4):
        raise PatchError("Unsupported bootstrap format")
    try:
        encoded = b"".join((folder / "bootstrap38.b64").read_bytes().split())
        payload = base64.b64decode(encoded, validate=True)
    except (ValueError, TypeError) as error:
        raise PatchError("Invalid bootstrap encoding") from error
    if (sha256(payload) != metadata.get("payload_sha256")
            or sha256((folder / "bootstrap.py").read_bytes()) != metadata.get("source_sha256")):
        raise PatchError("Bootstrap integrity mismatch; regenerate it with Python 3.8")
    return payload


def _excluded(path):
    name = path.name.lower()
    return (name in {SOURCE_EXE.lower(), OUTPUT_EXE.lower(), "sync_light.original.marshal",
                     "jonsbo-profile.json", "manual-led-profile.json", "rgb-diagnostic.jsonl", "addon-install.json",
                     ".git", "__pycache__", *PAYLOAD_FILES}
            or name.startswith("unins") or name.startswith("compatibility-")
            or path.suffix.lower() in {".log", ".jsonl", ".pyc"})


def _check_runtime_tree(source):
    # Reject symlinks/junctions instead of traversing outside the supplied app.
    for current, directories, files in os.walk(str(source), followlinks=False):
        directories[:] = [name for name in directories if not _excluded(Path(name))]
        for name in directories + files:
            path = Path(current) / name
            if _excluded(path):
                continue
            info = path.lstat()
            if path.is_symlink() or getattr(info, "st_file_attributes", 0) & 0x400:
                raise PatchError("Linked runtime entries are not supported: " + str(path))


def _plain_path(path, label):
    """Reject links before resolve() can hide them, including parent junctions."""
    path = Path(os.path.abspath(os.path.expanduser(str(path))))
    for candidate in (path, *path.parents):
        try:
            info = candidate.lstat()
        except FileNotFoundError:
            continue
        except OSError as error:
            raise PatchError("Cannot inspect %s path: %s" % (label, candidate)) from error
        if candidate.is_symlink() or getattr(info, "st_file_attributes", 0) & 0x400:
            raise PatchError("Linked %s paths are not supported: %s" % (label, candidate))
    return path.resolve()


def preflight_install(source, destination, require_parent=True):
    """Validate every input and prepare output bytes without writing any files."""
    source = _plain_path(source, "source")
    destination = _plain_path(destination, "destination")
    if os.path.lexists(str(destination)):
        raise PatchError("Destination already exists; choose a new folder")
    if destination == source or source in destination.parents or destination in source.parents:
        raise PatchError("Source and destination must be disjoint")
    resource_root = ROOT.resolve()
    if (destination == resource_root or resource_root in destination.parents
            or destination in resource_root.parents):
        raise PatchError("Keep generated vendor files outside the add-on source folder")
    if require_parent and not destination.parent.is_dir():
        raise PatchError("Destination parent folder must already exist")
    ancestor = destination.parent
    while not ancestor.exists():
        ancestor = ancestor.parent
    if not ancestor.is_dir():
        raise PatchError("Destination parent must be a folder")
    _plain_path(source / SOURCE_EXE, "source executable")
    data = verified_source(source)
    missing = [name for name in REQUIRED_RUNTIME
               if not ((source / name).is_file() if name.endswith((".dll", ".zip"))
                       else (source / name).is_dir())]
    if missing:
        raise PatchError("Source is missing runtime files: " + ", ".join(missing))
    for name in ("bootstrap.py", "bootstrap38.b64", "bootstrap38.json"):
        _plain_path(ROOT / name, "add-on resource")
    for name in PAYLOAD_FILES:
        _plain_path(ROOT / "payload" / name, "add-on resource")
    bootstrap = load_bootstrap()
    payloads = {name: (ROOT / "payload" / name).read_bytes() for name in PAYLOAD_FILES}
    _check_runtime_tree(source)
    patched, original = repack_archive(data, bootstrap)
    return PreparedInstall(source, destination, data, patched, original, payloads)


def install_addon(source, destination, progress=None, create_parent=False):
    """Install only after full preflight; optional parent creation is for the GUI."""
    def report(stage, message):
        if progress is not None:
            progress(stage, message)

    report("validate", "Checking the original application and add-on files")
    prepared = preflight_install(source, destination, require_parent=not create_parent)
    source, destination = prepared.source, prepared.destination
    data, patched = prepared.original_data, prepared.patched_data
    report("copy", "Copying the locally installed Umbra runtime")
    if create_parent:
        destination.parent.mkdir(parents=True, exist_ok=True)
        # Check again after parent creation, before exclusive output creation.
        _plain_path(destination, "destination")
    destination.mkdir()  # Exclusive creation; never overwrite existing output.
    for path in source.iterdir():
        if _excluded(path):
            continue
        target = destination / path.name
        if path.is_dir():
            shutil.copytree(str(path), str(target),
                            ignore=lambda parent, names: [n for n in names if _excluded(Path(n))])
        else:
            shutil.copy2(str(path), str(target))
    report("patch", "Adding the RGB add-on to the separate application copy")
    for name, payload in prepared.payloads.items():
        (destination / name).write_bytes(payload)
    (destination / "Sync_light.original.marshal").write_bytes(prepared.original_main)
    (destination / OUTPUT_EXE).write_bytes(patched)
    manifest = {"addon_version": VERSION, "vendor_version": SUPPORTED_VERSION,
                "source_sha256": sha256(data), "patched_sha256": sha256(patched),
                "payload_sha256": {name: sha256(payload) for name, payload in prepared.payloads.items()},
                "rgb_only": True, "manual_port": 1, "count_written_to_hub": False}
    (destination / "addon-install.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if (source / SOURCE_EXE).read_bytes() != data:
        raise PatchError("Original executable changed concurrently; do not use this output")
    report("complete", "The separate application copy is ready")
    return manifest


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", action="version", version=VERSION)
    commands = parser.add_subparsers(dest="command", required=True)
    inspect = commands.add_parser("inspect", help="Read-only check of the original app")
    inspect.add_argument("--source", required=True, type=Path)
    install = commands.add_parser("install", help="Create an isolated app copy; never opens hardware")
    install.add_argument("--source", required=True, type=Path)
    install.add_argument("--destination", required=True, type=Path)
    args = parser.parse_args(argv)
    try:
        if args.command == "inspect":
            data = verified_source(args.source)
            print(json.dumps({"supported": True, "vendor_version": SUPPORTED_VERSION,
                              "source_sha256": sha256(data), "addon_version": VERSION}, indent=2))
        else:
            result = install_addon(args.source, args.destination)
            print(json.dumps(result, indent=2))
            print("Created:", args.destination / OUTPUT_EXE)
            print("Original unchanged. No device was opened and no LED count was written.")
    except (PatchError, OSError, ValueError) as error:
        print("ERROR:", error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
